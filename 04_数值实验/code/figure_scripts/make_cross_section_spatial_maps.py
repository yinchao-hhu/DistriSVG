"""Create reproducible cross-section spatial maps and source-data audits.

The PDAC manuscript panel separates the shared SPOTlight Ductal-composition map
from gene-specific expression. For each displayed gene and section, log-CP10K
expression is regressed on the Ductal weight and the standardized residual is
drawn at every observed spot. No binning, interpolation, or smoothing is used.
The maps are descriptive observed-data checks, not fitted coefficient surfaces.

The normalized mouse diagnostic is retained only for provenance; the manuscript
mouse figure is generated by make_mouse_region_overlays.py on section-matched
H&E images.
"""

