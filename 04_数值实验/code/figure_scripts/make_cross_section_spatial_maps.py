def pdac_candidate_table() -> pd.DataFrame:
    path = ROOT / "overleaf" / "figs" / "pdac_basis_consensus_candidates.csv"
    table = pd.read_csv(path, low_memory=False)
    table = table[table["Joint_Basis_Q"] < 0.05].copy()
    return table.head(1000).reset_index(drop=True)


def load_pdac_inputs(candidates: pd.DataFrame) -> dict[str, pd.DataFrame]:
    genes = set(candidates["Gene"].astype(str))
    cell_types = set(candidates["Cell_Type_Name"].astype(str))
    frames: dict[str, pd.DataFrame] = {}
    for section in PDAC_SLICES:
        expression_full = pd.read_csv(PDAC_EXPR_DIR / f"{section}_processed_data_mincell5.csv")
        expression_full["library_size"] = expression_full.drop(columns=["Spot_ID"]).sum(axis=1)
        expression = expression_full[["Spot_ID", "library_size", *sorted(genes)]].copy()
        omega = pd.read_csv(
            PDAC_OMEGA_DIR / f"{section}_SPOTlight_W_omega_with_xy.csv",
            usecols=lambda column: column in {"spot", "x", "y"} or column in cell_types,
        )
        frame = expression.merge(omega, left_on="Spot_ID", right_on="spot", how="inner", validate="one_to_one")
        frames[section] = frame
    return frames


def pdac_proxy(frame: pd.DataFrame, gene: str, cell_type: str) -> np.ndarray:
    normalized = frame[gene].to_numpy(dtype=float) / frame["library_size"].to_numpy(dtype=float).clip(1.0) * 1e4
    return np.log1p(normalized) * frame[cell_type].to_numpy(dtype=float)


def score_pdac_candidate(row: pd.Series, frames: dict[str, pd.DataFrame]) -> CandidateMaps:
    maps = {
        section: smoothed_rank_map(normalize_xy(frames[section]), pdac_proxy(frames[section], str(row.Gene), str(row.Cell_Type_Name)), bins=24, sigma=0.65)
        for section in PDAC_SLICES
    }
    score_a = mean_pairwise(maps[section] for section in PDAC_GROUPS[0][1])
    score_b = mean_pairwise(maps[section] for section in PDAC_GROUPS[1][1])
    score_all = mean_pairwise(maps.values())
    balanced = np.nanmin([score_a, score_b]) if np.isfinite(score_a) and np.isfinite(score_b) else -np.inf
    score = 0.65 * balanced + 0.35 * np.nanmean([score_a, score_b])
    return CandidateMaps(
        gene=str(row.Gene),
        cell_type=str(row.Cell_Type_Name),
        rank=float(row.Joint_Basis_Rank),
        score=float(score),
        within_a=float(score_a),
        within_b=float(score_b),
        across_sections=float(score_all),
        maps=maps,
    )


def select_pdac_candidates() -> tuple[list[CandidateMaps], pd.DataFrame, dict[str, pd.DataFrame]]:
    candidates = pdac_candidate_table()
    selected_rows = []
    selection: list[CandidateMaps] = []
    for gene in PDAC_DUCTAL_VISUALIZATION_GENES:
        options = candidates[
            candidates["Gene"].astype(str).eq(gene)
            & candidates["Cell_Type_Name"].astype(str).eq("Ductal")
        ].sort_values("Joint_Basis_Rank")
        if options.empty:
            raise RuntimeError(f"Expected Ductal candidate {gene} was not present in the PDAC consensus ranking.")
        row = options.iloc[0]
        selected_rows.append(row)
        selection.append(
            CandidateMaps(
                gene=gene,
                cell_type="Ductal",
                rank=float(row.Joint_Basis_Rank),
                score=float(-row.Joint_Basis_Rank),
                within_a=None,
                within_b=None,
                across_sections=None,
                maps={},
            )
        )
    selected_table = pd.DataFrame(selected_rows).reset_index(drop=True)
    frames = load_pdac_inputs(selected_table)
    table = pd.DataFrame(
        [
            {
                "gene": item.gene,
                "cell_type": item.cell_type,
                "joint_basis_rank": item.rank,
                "selected_for_figure": True,
                "selection_rule": "fixed display panel retained from the prior manuscript visualization; not part of the joint-basis test",
            }
            for item in selection
        ]
    ).sort_values("joint_basis_rank")
    return selection, table, frames


def read_mouse_expression(section: str, folder: str, genes: list[str]) -> pd.DataFrame:
    import scanpy as sc

    adata = sc.read_10x_h5(MOUSE_DATA_DIR / folder / "filtered_feature_bc_matrix.h5", gex_only=False)
    adata.var_names_make_unique()
    indices = adata.var_names.get_indexer(genes)
    valid = indices >= 0
    matrix = adata.X[:, indices[valid]]
    matrix = matrix.toarray() if sparse.issparse(matrix) else np.asarray(matrix)
    library_size = np.asarray(adata.X.sum(axis=1)).ravel().astype(float)
    expression = np.log1p(matrix / (library_size[:, None] + 1e-10) * 1e4)
    out = pd.DataFrame(expression, columns=np.asarray(genes)[valid])
    out.insert(0, "spot_id", adata.obs_names.astype(str))
    return out


def mouse_candidate_table() -> pd.DataFrame:
    table = pd.read_csv(MOUSE_OMEGA_DIR / "mouse_reference_nnls_ctsv_ranking.csv")
