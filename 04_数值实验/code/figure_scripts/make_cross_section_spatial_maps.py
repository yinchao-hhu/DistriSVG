def pdac_input_audit(frames: dict[str, pd.DataFrame]) -> dict[str, dict[str, float | int | str]]:
    audit = {}
    for section, frame in frames.items():
        expression_path = PDAC_EXPR_DIR / f"{section}_processed_data_mincell5.csv"
        omega_path = PDAC_OMEGA_DIR / f"{section}_SPOTlight_W_omega_with_xy.csv"
        audit[section] = {
            "expression_file": str(expression_path.relative_to(ROOT)),
            "expression_sha256": sha256(expression_path),
            "omega_file": str(omega_path.relative_to(ROOT)),
            "omega_sha256": sha256(omega_path),
            "merged_spots": int(len(frame)),
            "unique_spot_ids": int(frame["Spot_ID"].nunique()),
            "unique_coordinates": int(frame[["x", "y"]].drop_duplicates().shape[0]),
            "median_library_size": float(frame["library_size"].median()),
        }
    return audit


def short_pdac_section(section: str) -> str:
    return section.replace("PDAC_", "")


def draw_map_figure(
    selected: list[CandidateMaps],
    sections: list[str],
    labels: list[str],
    title: str,
    stem: str,
    group_headers: list[tuple[str, int, int]] | None,
    score_label: str,
) -> None:
    rows = len(selected)
    fig = plt.figure(figsize=(7.2, 1.33 * rows + 0.75))
    grid = fig.add_gridspec(rows, len(sections) + 1, width_ratios=[1.15] + [1] * len(sections), hspace=0.22, wspace=0.06)
    cmap = plt.get_cmap("viridis").copy()
    cmap.set_bad("#F7F7F7")
    image = None
    for row_index, item in enumerate(selected):
        label_axis = fig.add_subplot(grid[row_index, 0])
        label_axis.axis("off")
        label_axis.text(0.0, 0.67, item.gene, ha="left", va="center", fontsize=7.4, fontweight="bold")
        label_axis.text(0.0, 0.43, item.cell_type.replace(".clone.", " "), ha="left", va="center", fontsize=5.8, color="#454545")
        if score_label == "Across-section":
            score = item.across_sections
        elif score_label == "Tumor B":
            score = item.within_b
        else:
            score = min(item.within_a if item.within_a is not None else np.nan, item.within_b if item.within_b is not None else np.nan)
        label_axis.text(0.0, 0.19, f"{score_label} r={score:.2f}", ha="left", va="center", fontsize=5.2, color="#6A6A6A")
        for column_index, section in enumerate(sections, start=1):
            axis = fig.add_subplot(grid[row_index, column_index])
            image = axis.imshow(item.maps[section], origin="lower", interpolation="nearest", cmap=cmap, vmin=0.0, vmax=1.0)
            axis.set_xticks([])
            axis.set_yticks([])
            for spine in axis.spines.values():
                spine.set_color("#D8D8D8")
                spine.set_linewidth(0.45)
            if row_index == 0:
                axis.set_title(labels[column_index - 1], pad=2, fontsize=6.1, fontweight="bold")
    colorbar = fig.colorbar(image, ax=fig.axes, fraction=0.013, pad=0.015)
    colorbar.set_label("Smoothed proxy percentile", fontsize=6)
    colorbar.ax.tick_params(labelsize=5.4, length=2)
    fig.suptitle(title, x=0.51, y=1.01, fontsize=8.2, fontweight="bold")
    if group_headers:
        for text, start, stop in group_headers:
            x0 = 0.16 + start / len(sections) * 0.74
            x1 = 0.16 + stop / len(sections) * 0.74
            fig.text((x0 + x1) / 2, 0.952, text, ha="center", va="bottom", fontsize=6.0, color="#555555")
    fig.text(0.01, 0.987, "a", fontsize=9, fontweight="bold", va="top")
    export_figure(fig, stem)


def write_qa_notes(
    pdac_selected: list[CandidateMaps],
    moran: pd.DataFrame,
    similarity: pd.DataFrame,
    mouse_selected: list[CandidateMaps],
) -> None:
    raw_means = similarity.groupby("section")["legacy_proxy_pearson_r"].mean()
    adjusted_means = similarity.groupby("section")["adjusted_residual_pearson_r"].mean()
    lines = [
        "# Cross-Section Spatial-Map QA Notes",
        "",
        "## Figure Contract",
        "",
        "- Core conclusion: the displayed PDAC genes retain spatially autocorrelated expression after the shared Ductal-composition field is removed, but their residual patterns are gene- and section-specific rather than recurrent replicas.",
        "- Backend: Python/matplotlib only.",
        "- PDAC selection: four pre-specified biologically interpretable Ductal candidates from the joint five-basis ranking are visualized in the Tumor B serial-section triplet.",
        "- Mouse legacy diagnostic: normalized-grid concordance is retained only for provenance. The manuscript mouse panel is generated separately on native H&E images and is interpreted section by section.",
        "- PDAC manuscript maps: panel a shows the SPOTlight Ductal weight; panel b shows the within-section standardized residual from regressing log(CP10K+1) on that weight.",
        "- Every square is one observed spot. No spatial binning, interpolation, or smoothing is used in the displayed panel.",
        "- No local/manual image adjustments were applied.",
        "",
        "## PDAC audit",
        "",
    ]
    for item in pdac_selected:
        gene_moran = moran[moran["gene"].eq(item.gene)]
        lines.append(
            f"- {item.gene}/{item.cell_type}, joint rank {int(item.rank)}: "
            f"Moran's I={gene_moran['morans_i'].min():.3f}-{gene_moran['morans_i'].max():.3f} across B_ST1-B_ST3."
        )
    lines += [
        "",
        f"- Across all 12 residual maps, Moran's I={moran['morans_i'].min():.3f}-{moran['morans_i'].max():.3f}; maximum BH q={moran['bh_q_across_12_maps'].max():.4f}.",
        "- Moran's I uses a directed, non-symmetrized binary 6-NN graph from scipy.spatial.cKDTree.query(k=7), with self dropped and distance ties following the returned source-row index order. Each row has six unit weights, so uniform row standardization would leave I unchanged.",
        "- The BH adjustment is conditional on the retained four-gene display panel and does not account for gene selection.",
    ]
    for section in PDAC_GROUPS[1][1]:
        lines.append(
            f"- {short_pdac_section(section)} mean cross-gene Pearson r: "
            f"legacy weighted proxy={raw_means.loc[section]:.3f}; composition-adjusted residual={adjusted_means.loc[section]:.3f}."
        )
    lines += ["", "## Mouse candidates", ""]
    for item in mouse_selected:
        lines.append(f"- {item.gene}/{item.cell_type}: mean three-section r={item.across_sections:.3f}; max abs beta={item.rank:.3f}.")
    lines += ["", "## Exports", "", "- SVG keeps editable text; PDF uses TrueType text; TIFF is exported at 600 dpi."]
    (FIG_DIR / "cross_section_maps_qa_notes.md").write_text("\n".join(lines) + "\n", encoding="utf-8")


def main() -> None:
    parser = argparse.ArgumentParser(description="Create PDAC and mouse cross-section spatial maps.")
    parser.add_argument("--pdac-only", action="store_true")
    parser.add_argument("--mouse-only", action="store_true")
    args = parser.parse_args()
    if args.pdac_only and args.mouse_only:
        raise ValueError("Choose at most one data set.")
    FIG_DIR.mkdir(parents=True, exist_ok=True)
    SOURCE_DIR.mkdir(parents=True, exist_ok=True)
    configure_matplotlib()

    pdac_selected: list[CandidateMaps] = []
    mouse_selected: list[CandidateMaps] = []
    pdac_moran = pd.DataFrame()
    pdac_similarity = pd.DataFrame()
    if not args.mouse_only:
        pdac_selected, pdac_scores, pdac_frames = select_pdac_candidates()
        pdac_scores.to_csv(SOURCE_DIR / "fig5_pdac_candidate_concordance.csv", index=False)
        spot_source = pdac_spot_source(pdac_selected, pdac_frames)
        spot_source.to_csv(SOURCE_DIR / "fig5_pdac_spot_values.csv", index=False)
        pdac_similarity = pdac_similarity_audit(spot_source)
        pdac_similarity.to_csv(SOURCE_DIR / "fig5_pdac_row_similarity_audit.csv", index=False)
        pdac_moran = pdac_moran_audit(spot_source)
        pdac_moran.to_csv(SOURCE_DIR / "fig5_pdac_moran_audit.csv", index=False)
        draw_pdac_spot_figure(pdac_selected, spot_source, pdac_moran)
        (SOURCE_DIR / "fig5_pdac_input_audit.json").write_text(
            json.dumps(pdac_input_audit(pdac_frames), indent=2) + "\n", encoding="utf-8"
        )
        print("PDAC selected:", ", ".join(f"{item.gene}/{item.cell_type}" for item in pdac_selected))
    if not args.pdac_only:
        mouse_selected, mouse_scores, _ = select_mouse_candidates()
        mouse_scores.to_csv(SOURCE_DIR / "fig6_mouse_candidate_concordance.csv", index=False)
        write_surface_data("fig6_mouse", mouse_selected)
        draw_map_figure(
            mouse_selected,
            list(MOUSE_SECTIONS),
            [MOUSE_LABELS[section] for section in MOUSE_SECTIONS],
            "Legacy normalized-coordinate mouse diagnostic (not used in manuscript)",
            "fig6_mouse_normalized_map_diagnostic",
            None,
            "Across-section",
        )
        print("Mouse selected:", ", ".join(f"{item.gene}/{item.cell_type}" for item in mouse_selected))
    if pdac_selected:
        write_qa_notes(pdac_selected, pdac_moran, pdac_similarity, mouse_selected)
    manifest = {
        "pdac_visualization_genes": list(PDAC_DUCTAL_VISUALIZATION_GENES),
        "mouse_selection_cell_groups": list(MOUSE_CELL_GROUPS),
        "pdac_sections": list(PDAC_SLICES),
        "pdac_display": "panel a: direct SPOTlight Ductal weights; panel b: direct spot-level standardized residuals from log(CP10K+1) regressed on Ductal weight; no binning, interpolation, or smoothing",
        "pdac_spatial_audit": "6-nearest-neighbor Moran's I with 999 one-sided permutations and BH correction across the 12 displayed residual maps",
        "moran_weight_definition": "directed non-symmetrized binary 6-NN from scipy.spatial.cKDTree.query(k=7), self dropped; ties follow returned source-row index order; fixed out-degree means uniform row standardization leaves I unchanged",
        "legacy_pdac_diagnostics_not_used_in_manuscript": [
            "fig4_pdac_composition_adjusted.csv (16x16 smoothed diagnostic)",
            "fig4_pdac_fitted_spatial_effect.csv (two-basis fitted-surface diagnostic)",
            "fig5_pdac_spatial_surfaces.csv (legacy weighted-proxy selection surface)",
        ],
        "mouse_sections": list(MOUSE_SECTIONS),
    }
    (SOURCE_DIR / "cross_section_maps_manifest.json").write_text(json.dumps(manifest, indent=2), encoding="utf-8")
    print(f"Wrote outputs to {FIG_DIR}")


if __name__ == "__main__":
    main()
