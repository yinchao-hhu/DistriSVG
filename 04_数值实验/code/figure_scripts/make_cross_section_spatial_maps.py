def normalize_xy(frame: pd.DataFrame) -> np.ndarray:
    coords = frame[["x", "y"]].to_numpy(dtype=float)
    low = coords.min(axis=0)
    high = coords.max(axis=0)
    return (coords - low) / (high - low + 1e-10)


def rank_normalize(values: np.ndarray) -> np.ndarray:
    out = values.copy()
    valid = np.isfinite(values)
    if valid.sum() < 4:
        return out
    series = pd.Series(values[valid])
    out[valid] = series.rank(method="average", pct=True).to_numpy()
    return out


def smoothed_rank_map(coords: np.ndarray, values: np.ndarray, bins: int, sigma: float) -> np.ndarray:
    """Return an occupancy-masked, smoothed proxy percentile map."""
    x_index = np.clip((coords[:, 0] * bins).astype(int), 0, bins - 1)
    y_index = np.clip((coords[:, 1] * bins).astype(int), 0, bins - 1)
    numerator = np.zeros((bins, bins), dtype=float)
    denominator = np.zeros((bins, bins), dtype=float)
    np.add.at(numerator, (y_index, x_index), values)
    np.add.at(denominator, (y_index, x_index), 1.0)
    smooth_num = gaussian_filter(numerator, sigma=sigma, mode="nearest")
    smooth_den = gaussian_filter(denominator, sigma=sigma, mode="nearest")
    surface = smooth_num / np.maximum(smooth_den, 1e-12)
    support = gaussian_filter(denominator, sigma=sigma, mode="nearest") > 0.035
    surface[~support] = np.nan
    return rank_normalize(surface)


def safe_correlation(left: np.ndarray, right: np.ndarray) -> float:
    mask = np.isfinite(left) & np.isfinite(right)
    if mask.sum() < 12:
        return float("nan")
    a = left[mask]
    b = right[mask]
    if np.std(a) < 1e-10 or np.std(b) < 1e-10:
        return float("nan")
    return float(np.corrcoef(a, b)[0, 1])


def mean_pairwise(maps: Iterable[np.ndarray]) -> float:
    items = list(maps)
    values = [safe_correlation(items[i], items[j]) for i in range(len(items)) for j in range(i + 1, len(items))]
    valid = [value for value in values if np.isfinite(value)]
    return float(np.mean(valid)) if valid else float("nan")


def excluded_gene(gene: str) -> bool:
    return gene in EXCLUDE_GENES or gene.startswith(EXCLUDE_GENE_PREFIXES)


