def load_mouse_inputs(candidates: pd.DataFrame) -> dict[str, pd.DataFrame]:
    genes = candidates["Gene"].drop_duplicates().astype(str).tolist()
    frames: dict[str, pd.DataFrame] = {}
    for section, folder in MOUSE_SECTIONS.items():
        expression = read_mouse_expression(section, folder, genes)
        omega = pd.read_csv(MOUSE_OMEGA_DIR / f"mouse_reference_nnls_omega_{section}.csv")
        frames[section] = omega.merge(expression, on="spot_id", how="inner", validate="one_to_one")
    return frames


def mouse_proxy(frame: pd.DataFrame, gene: str, cell_type: str) -> np.ndarray:
    return frame[gene].to_numpy(dtype=float) * frame[cell_type].to_numpy(dtype=float)


def score_mouse_candidate(row: pd.Series, frames: dict[str, pd.DataFrame]) -> CandidateMaps:
    maps = {
        section: smoothed_rank_map(normalize_xy(frames[section]), mouse_proxy(frames[section], str(row.Gene), str(row.Cell_Type_Name)), bins=26, sigma=1.15)
        for section in MOUSE_SECTIONS
    }
    concordance = mean_pairwise(maps.values())
    return CandidateMaps(
        gene=str(row.Gene),
        cell_type=str(row.Cell_Type_Name),
        rank=float(row.Abs_Beta_Max),
        score=float(concordance),
        within_a=None,
        within_b=None,
        across_sections=float(concordance),
        maps=maps,
    )


def select_mouse_candidates() -> tuple[list[CandidateMaps], pd.DataFrame, dict[str, pd.DataFrame]]:
    candidates = mouse_candidate_table()
    frames = load_mouse_inputs(candidates)
    scored = [score_mouse_candidate(row, frames) for _, row in candidates.iterrows() if not excluded_gene(str(row.Gene))]
    selection = []
    for cell_type in MOUSE_CELL_GROUPS:
        options = [item for item in scored if item.cell_type == cell_type and np.isfinite(item.score)]
        if options:
            selection.append(max(options, key=lambda item: (item.score, item.rank)))
    table = pd.DataFrame(
        [
            {
                "gene": item.gene,
                "cell_type": item.cell_type,
                "abs_beta_max": item.rank,
                "mean_map_r": item.across_sections,
                "selected_for_fig7": (item.gene, item.cell_type) in {(x.gene, x.cell_type) for x in selection},
            }
            for item in scored
        ]
    ).sort_values("mean_map_r", ascending=False)
    return selection[:4], table, frames


def write_surface_data(kind: str, selected: list[CandidateMaps]) -> None:
    rows = []
    for item in selected:
        for section, surface in item.maps.items():
            for y_index in range(surface.shape[0]):
                for x_index in range(surface.shape[1]):
                    rows.append(
                        {
                            "gene": item.gene,
                            "cell_type": item.cell_type,
                            "section": section,
                            "x_bin": x_index,
                            "y_bin": y_index,
                            "smoothed_proxy_percentile": surface[y_index, x_index],
                        }
                    )
    pd.DataFrame(rows).to_csv(SOURCE_DIR / f"{kind}_spatial_surfaces.csv", index=False)


def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def percentile(values: np.ndarray) -> np.ndarray:
    return pd.Series(values).rank(method="average", pct=True).to_numpy(dtype=float)


def bh_adjust(p_values: np.ndarray) -> np.ndarray:
    p_values = np.asarray(p_values, dtype=float)
    order = np.argsort(p_values)
    ranked = p_values[order] * len(p_values) / np.arange(1, len(p_values) + 1)
    ranked = np.minimum.accumulate(ranked[::-1])[::-1]
    adjusted = np.empty_like(ranked)
    adjusted[order] = np.clip(ranked, 0.0, 1.0)
    return adjusted


def pdac_spot_source(selected: list[CandidateMaps], frames: dict[str, pd.DataFrame]) -> pd.DataFrame:
    """Return direct spot values with the Ductal-composition effect separated."""
    rows = []
    for item in selected:
        for section in PDAC_GROUPS[1][1]:
            frame = frames[section]
            counts = frame[item.gene].to_numpy(dtype=float)
            library_size = frame["library_size"].to_numpy(dtype=float)
            normalized_expression = np.log1p(counts / np.maximum(library_size, 1.0) * 1e4)
            weights = frame[item.cell_type].to_numpy(dtype=float)
            design = np.column_stack([np.ones(len(frame)), weights])
            coefficients = np.linalg.lstsq(design, normalized_expression, rcond=None)[0]
            fitted_composition = design @ coefficients
            residual = normalized_expression - fitted_composition
            residual_sd = float(np.std(residual, ddof=1))
            residual_z = residual / residual_sd if residual_sd > 1e-12 else np.zeros_like(residual)
            raw_proxy = normalized_expression * weights
            for index in range(len(frame)):
                rows.append(
                    {
                        "gene": item.gene,
                        "cell_type": item.cell_type,
                        "joint_basis_rank": int(item.rank),
                        "section": section,
                        "spot_id": frame["Spot_ID"].iloc[index],
                        "x": float(frame["x"].iloc[index]),
                        "y": float(frame["y"].iloc[index]),
                        "filtered_count": float(counts[index]),
                        "library_size": float(library_size[index]),
                        "log_cp10k": float(normalized_expression[index]),
                        "ductal_weight": float(weights[index]),
                        "composition_intercept": float(coefficients[0]),
                        "composition_slope": float(coefficients[1]),
                        "fitted_composition_component": float(fitted_composition[index]),
                        "composition_adjusted_residual": float(residual[index]),
                        "composition_adjusted_z": float(residual_z[index]),
                        "legacy_weighted_expression_proxy": float(raw_proxy[index]),
                    }
                )
    return pd.DataFrame(rows)


def pdac_similarity_audit(source: pd.DataFrame) -> pd.DataFrame:
    """Compare cross-gene similarity before and after composition adjustment."""
    rows = []
    for section, section_table in source.groupby("section"):
        raw = section_table.pivot(index="spot_id", columns="gene", values="legacy_weighted_expression_proxy")
        adjusted = section_table.pivot(index="spot_id", columns="gene", values="composition_adjusted_z")
        genes = list(adjusted.columns)
        for left_index, left in enumerate(genes):
            for right in genes[left_index + 1 :]:
                rows.append(
                    {
                        "section": section,
                        "gene_left": left,
                        "gene_right": right,
                        "legacy_proxy_pearson_r": float(raw[left].corr(raw[right], method="pearson")),
                        "legacy_proxy_spearman_r": float(raw[left].corr(raw[right], method="spearman")),
                        "adjusted_residual_pearson_r": float(adjusted[left].corr(adjusted[right], method="pearson")),
                        "adjusted_residual_spearman_r": float(adjusted[left].corr(adjusted[right], method="spearman")),
                    }
                )
    return pd.DataFrame(rows)


def moran_knn(values: np.ndarray, coordinates: np.ndarray, rng: np.random.Generator, k: int = 6, permutations: int = 999) -> tuple[float, float]:
    values = np.asarray(values, dtype=float)
    centered = values - np.mean(values)
    denominator = float(np.mean(centered * centered))
    if denominator <= 1e-14:
        return float("nan"), 1.0
    tree = cKDTree(np.asarray(coordinates, dtype=float))
    _, neighbor_indices = tree.query(coordinates, k=min(k + 1, len(values)))
    neighbor_indices = neighbor_indices[:, 1:]

    def statistic(vector: np.ndarray) -> float:
        return float(np.mean(vector[:, None] * vector[neighbor_indices]) / denominator)

    observed = statistic(centered)
    null = np.empty(permutations, dtype=float)
    for index in range(permutations):
        null[index] = statistic(rng.permutation(centered))
    p_value = (1 + int(np.sum(null >= observed))) / (permutations + 1)
    return observed, float(p_value)


def pdac_moran_audit(source: pd.DataFrame, k: int = 6, permutations: int = 999) -> pd.DataFrame:
    rows = []
    for gene_index, gene in enumerate(PDAC_DUCTAL_VISUALIZATION_GENES):
        for section_index, section in enumerate(PDAC_GROUPS[1][1]):
            group = source[source["gene"].eq(gene) & source["section"].eq(section)]
            rng = np.random.default_rng(20260807 + gene_index * 100 + section_index)
            statistic, p_value = moran_knn(
                group["composition_adjusted_z"].to_numpy(dtype=float),
                group[["x", "y"]].to_numpy(dtype=float),
                rng,
                k=k,
                permutations=permutations,
            )
            rows.append(
                {
                    "gene": gene,
                    "cell_type": "Ductal",
                    "section": section,
                    "n_spots": len(group),
                    "knn_k": k,
                    "permutations": permutations,
                    "weight_definition": "directed binary kNN; w_ij=1 when j is returned among i's k nearest neighbours; not symmetrized",
                    "row_standardized": False,
                    "tie_breaking": "scipy.spatial.cKDTree.query return order on released source-row coordinates after dropping self",
                    "scipy_version": scipy.__version__,
                    "morans_i": statistic,
                    "one_sided_permutation_p": p_value,
                }
            )
    audit = pd.DataFrame(rows)
    audit["bh_q_across_12_maps"] = bh_adjust(audit["one_sided_permutation_p"].to_numpy())
    return audit


