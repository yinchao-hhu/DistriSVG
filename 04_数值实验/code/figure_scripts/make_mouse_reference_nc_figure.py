#!/usr/bin/env python3
"""Make a Nature Communications-style Mouse Brain reference deconvolution figure.

Inputs are the reference NNLS deconvolution outputs generated by
run_mouse_reference_deconvolution.py. The figure is designed as a two-column
manuscript panel with editable vector text and traceable source data.
"""

from __future__ import annotations

import json
from pathlib import Path

import matplotlib as mpl
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd
from matplotlib import patches
from matplotlib.lines import Line2D


ROOT = Path(__file__).resolve().parents[2]
IN_DIR = ROOT / "overleaf" / "figs" / "mouse_reference_deconv"
FIG_DIR = ROOT / "overleaf" / "figs" / "mouse_reference_deconv_nc"
SOURCE_DIR = FIG_DIR / "source_data"
TABLE_DIR = ROOT / "overleaf" / "tables"
for path in [FIG_DIR, SOURCE_DIR, TABLE_DIR]:
    path.mkdir(parents=True, exist_ok=True)

FIG_BASE = FIG_DIR / "fig5_mouse_brain_reference_deconv"

CELL_TYPES = [
    "Astrocyte",
    "Endothelial Cell",
    "GABA-ergic Neuron",
    "Glutamatergic Neuron",
    "Microglia",
    "Oligodendrocyte",
    "Oligodendrocyte Precursor Cell",
]

CELL_TYPE_SHORT = {
    "Astrocyte": "Astro",
    "Endothelial Cell": "Endo",
    "GABA-ergic Neuron": "GABA neuron",
    "Glutamatergic Neuron": "Glut neuron",
    "Microglia": "Microglia",
    "Oligodendrocyte": "Oligo",
    "Oligodendrocyte Precursor Cell": "OPC",
}

CELL_COLORS = {
    "Astrocyte": "#0072B2",
    "Endothelial Cell": "#E69F00",
    "GABA-ergic Neuron": "#009E73",
    "Glutamatergic Neuron": "#D55E00",
    "Microglia": "#CC79A7",
    "Oligodendrocyte": "#56B4E9",
    "Oligodendrocyte Precursor Cell": "#7A7A7A",
}

SECTION_ORDER = ["Anterior", "Posterior", "Anterior2"]
SECTION_LABELS = {
    "Anterior": "Anterior",
    "Posterior": "Posterior",
    "Anterior2": "Anterior rep.",
}


def configure_matplotlib() -> None:
    mpl.rcParams.update(
        {
            "font.family": "sans-serif",
            "font.sans-serif": ["Arial", "Helvetica", "DejaVu Sans", "sans-serif"],
            "svg.fonttype": "none",
            "pdf.fonttype": 42,
            "font.size": 6,
            "axes.labelsize": 6,
            "axes.titlesize": 6.5,
            "xtick.labelsize": 5.5,
            "ytick.labelsize": 5.5,
            "legend.fontsize": 5.2,
            "axes.linewidth": 0.55,
            "xtick.major.width": 0.55,
            "ytick.major.width": 0.55,
            "xtick.major.size": 2.2,
            "ytick.major.size": 2.2,
            "axes.spines.top": False,
            "axes.spines.right": False,
            "legend.frameon": False,
            "figure.dpi": 150,
        }
    )


def panel_label(ax, label: str, x: float = -0.12, y: float = 1.04) -> None:
    ax.text(
        x,
        y,
        label,
        transform=ax.transAxes,
        ha="left",
        va="bottom",
        fontsize=8,
        fontweight="bold",
        color="black",
    )


def load_inputs():
    ref_counts = pd.read_csv(IN_DIR / "mouse_reference_celltype_counts.csv")
    summary = pd.read_csv(IN_DIR / "mouse_reference_nnls_omega_summary.csv")
    history = pd.read_csv(IN_DIR / "mouse_reference_nnls_ctsv_history.csv")
    ranking = pd.read_csv(IN_DIR / "mouse_reference_nnls_ctsv_ranking.csv")
    gene_panel = pd.read_csv(IN_DIR / "mouse_reference_nnls_gene_panel.csv")
    manifest = json.loads((IN_DIR / "mouse_reference_deconv_manifest.json").read_text())
    omega = {}
    for section in SECTION_ORDER:
        df = pd.read_csv(IN_DIR / f"mouse_reference_nnls_omega_{section}.csv")
        df["section"] = section
        df["max_weight"] = df[CELL_TYPES].max(axis=1)
        omega[section] = df
    return ref_counts, summary, history, ranking, gene_panel, manifest, omega


def write_source_data(ref_counts, summary, history, ranking, gene_panel, omega) -> dict[str, Path]:
    paths = {}

    panel_b = ref_counts.copy()
    panel_b["cell_type_short"] = panel_b["cell_type"].map(CELL_TYPE_SHORT)
    paths["panel_b"] = SOURCE_DIR / "fig5b_reference_cell_counts.csv"
    panel_b.to_csv(paths["panel_b"], index=False)

    panel_c_rows = []
    for _, row in summary.iterrows():
        for ct in CELL_TYPES:
            panel_c_rows.append(
                {
                    "section": row["section"],
                    "section_label": SECTION_LABELS[row["section"]],
                    "cell_type": ct,
                    "cell_type_short": CELL_TYPE_SHORT[ct],
                    "mean_omega": row[f"mean_omega_{ct}"],
                    "dominant_count": row[f"dominant_count_{ct}"],
                    "n_spots": row["n_spots"],
                    "median_relative_residual": row["median_relative_residual"],
                    "mean_entropy": row["mean_entropy"],
                }
            )
    panel_c = pd.DataFrame(panel_c_rows)
    paths["panel_c"] = SOURCE_DIR / "fig5c_mean_reference_weights.csv"
    panel_c.to_csv(paths["panel_c"], index=False)

    panel_d = pd.concat(omega.values(), ignore_index=True)
    panel_d = panel_d[
        ["section", "spot_id", "x", "y", "dominant_ref_cell_type", "max_weight"]
        + CELL_TYPES
    ].copy()
    paths["panel_d"] = SOURCE_DIR / "fig5d_spatial_reference_weights.csv"
    panel_d.to_csv(paths["panel_d"], index=False)

    paths["panel_e"] = SOURCE_DIR / "fig5e_reference_apfedadam_history.csv"
    history.to_csv(paths["panel_e"], index=False)

    top = ranking.head(15).copy()
    top.insert(0, "rank", np.arange(1, len(top) + 1))
    top["cell_type_short"] = top["Cell_Type_Name"].map(CELL_TYPE_SHORT)
    paths["panel_f"] = SOURCE_DIR / "fig5f_top_reference_ctsv_pairs.csv"
    top.to_csv(paths["panel_f"], index=False)

    paths["gene_panel"] = SOURCE_DIR / "fig5_gene_panel_top800.csv"
    gene_panel.to_csv(paths["gene_panel"], index=False)
    return paths


def write_tables(ref_counts, summary, ranking) -> dict[str, Path]:
    paths = {}
    section_cols = [
        "section",
        "n_spots",
        "n_genes_used",
        "median_relative_residual",
        "mean_entropy",
    ] + [f"mean_omega_{ct}" for ct in CELL_TYPES]
    section_table = summary[section_cols].copy()
    for col in section_table.columns:
        if col.startswith("mean_omega") or col in ["median_relative_residual", "mean_entropy"]:
            section_table[col] = section_table[col].astype(float).round(3)
    paths["section_csv"] = TABLE_DIR / "table_mouse_reference_deconv_section_summary.csv"
    section_table.to_csv(paths["section_csv"], index=False)

    ref_table = ref_counts.copy()
    ref_table["cell_type_short"] = ref_table["cell_type"].map(CELL_TYPE_SHORT)
    paths["reference_csv"] = TABLE_DIR / "table_mouse_reference_deconv_reference_counts.csv"
    ref_table.to_csv(paths["reference_csv"], index=False)

    top_table = ranking.head(20).copy()
    top_table.insert(0, "rank", np.arange(1, len(top_table) + 1))
    top_table = top_table[
        ["rank", "Cell_Type_Name", "Gene", "Abs_Beta_Max", "Beta_h1", "Beta_h2", "Theta"]
    ].rename(
        columns={
            "Cell_Type_Name": "cell_type",
            "Gene": "gene",
            "Abs_Beta_Max": "abs_beta_max",
            "Beta_h1": "beta_h1",
            "Beta_h2": "beta_h2",
            "Theta": "theta",
        }
    )
    for col in ["abs_beta_max", "beta_h1", "beta_h2", "theta"]:
        top_table[col] = top_table[col].astype(float).round(4)
    paths["top_ctsv_csv"] = TABLE_DIR / "table_mouse_reference_deconv_top_ctsv_pairs.csv"
    top_table.to_csv(paths["top_ctsv_csv"], index=False)

    tex = [
        "% Auto-generated by code/figure_scripts/make_mouse_reference_nc_figure.py",
        "\\begin{table}[htbp]",
        "\\centering",
        "\\caption{\\textbf{Reference-based deconvolution summary for the mouse brain Visium application.} "
        "The reference was GEO GSE71585 Allen/Tasic mouse visual cortex scRNA-seq, using broad cell-type labels after QC. "
        "Weights are section-wise mean NNLS cell-type proportions.}",
        "\\label{tab:mouse-reference-deconv}",
        "\\begin{tabular}{lrrrrrr}",
        "\\toprule",
        "Section & Spots & Genes & Residual & Entropy & Glut. neuron & Oligodendrocyte \\\\",
        "\\midrule",
    ]
    for _, row in section_table.iterrows():
        tex.append(
            f"{row['section']} & {int(row['n_spots'])} & {int(row['n_genes_used'])} & "
            f"{row['median_relative_residual']:.3f} & {row['mean_entropy']:.3f} & "
            f"{row['mean_omega_Glutamatergic Neuron']:.3f} & "
            f"{row['mean_omega_Oligodendrocyte']:.3f} \\\\"
        )
    tex += [
        "\\bottomrule",
        "\\end{tabular}",
        "\\end{table}",
        "",
    ]
    paths["summary_tex"] = TABLE_DIR / "table_mouse_reference_deconv_summary.tex"
    paths["summary_tex"].write_text("\n".join(tex), encoding="utf-8")
    return paths


def draw_workflow(ax, manifest) -> None:
    ax.set_axis_off()
    panel_label(ax, "a", x=-0.03, y=1.00)
    ax.text(
        0.0,
        0.97,
        "Reference-derived cell-type weights",
        transform=ax.transAxes,
        ha="left",
        va="top",
        fontsize=6.8,
        fontweight="bold",
    )
    ax.text(
        0.0,
        0.78,
        "Matched mouse cortex scRNA profiles replace marker-score proxies with reproducible spot-level weights.",
        transform=ax.transAxes,
        ha="left",
        va="top",
        fontsize=5.35,
        color="#333333",
    )

    nodes = [
        ("GSE71585\nscRNA", 0.03, 0.35, 0.18, 0.24, "#F2F2F2"),
        ("Pseudobulk\nprofiles", 0.30, 0.35, 0.18, 0.24, "#E8F2FA"),
        ("NNLS\nspots", 0.58, 0.35, 0.14, 0.24, "#FDF0E6"),
        ("Omega", 0.82, 0.35, 0.13, 0.24, "#EEF7EE"),
    ]
    for text, x, y, w, h, color in nodes:
        rect = patches.FancyBboxPatch(
            (x, y),
            w,
            h,
            boxstyle="round,pad=0.012,rounding_size=0.015",
            transform=ax.transAxes,
            facecolor=color,
            edgecolor="#4D4D4D",
            linewidth=0.6,
        )
        ax.add_patch(rect)
        ax.text(x + w / 2, y + h / 2, text, transform=ax.transAxes, ha="center", va="center", fontsize=5.5)

    for i in range(len(nodes) - 1):
        _, x, y, w, h, _ = nodes[i]
        _, x2, y2, _, h2, _ = nodes[i + 1]
        ax.annotate(
            "",
            xy=(x2 - 0.015, y2 + h2 / 2),
            xytext=(x + w + 0.015, y + h / 2),
            xycoords=ax.transAxes,
            textcoords=ax.transAxes,
            arrowprops=dict(arrowstyle="-|>", lw=0.7, color="#4D4D4D", shrinkA=0, shrinkB=0),
        )

    ax.text(
        0.02,
        0.10,
        f"{manifest['n_reference_cells_used']} reference cells; {len(manifest['cell_types'])} cell types; 800 genes",
        transform=ax.transAxes,
        ha="left",
        va="center",
        fontsize=5.4,
        color="#333333",
    )


def draw_reference_counts(ax, ref_counts) -> None:
    panel_label(ax, "b", x=-0.20, y=1.02)
    data = ref_counts.copy()
    data["cell_type_short"] = data["cell_type"].map(CELL_TYPE_SHORT)
    data = data.sort_values("n_cells", ascending=True)
    y = np.arange(len(data))
    colors = [CELL_COLORS[c] for c in data["cell_type"]]
    ax.barh(y, data["n_cells"], color=colors, edgecolor="black", linewidth=0.35)
    ax.set_yticks(y)
    ax.set_yticklabels(data["cell_type_short"], fontsize=5.2)
    ax.set_xlabel("Reference cells (n)")
    ax.set_title("scRNA reference after QC", loc="left", pad=3, fontweight="bold", fontsize=6.3)
    ax.set_xlim(0, max(data["n_cells"]) * 1.18)
    for yi, value in zip(y, data["n_cells"]):
        ax.text(value + max(data["n_cells"]) * 0.015, yi, f"{int(value)}", va="center", ha="left", fontsize=5.1)


def draw_mean_weights(ax, summary) -> None:
    panel_label(ax, "c", x=-0.18, y=1.02)
    bottoms = np.zeros(len(SECTION_ORDER))
    x = np.arange(len(SECTION_ORDER))
    for ct in CELL_TYPES:
        values = []
        for section in SECTION_ORDER:
            row = summary.loc[summary["section"] == section].iloc[0]
            values.append(row[f"mean_omega_{ct}"])
        ax.bar(
            x,
            values,
            bottom=bottoms,
            color=CELL_COLORS[ct],
            edgecolor="white",
            linewidth=0.35,
            width=0.64,
            label=CELL_TYPE_SHORT[ct],
        )
        bottoms += np.asarray(values)
    ax.set_xticks(x)
    ax.set_xticklabels([SECTION_LABELS[s] for s in SECTION_ORDER], rotation=28, ha="right")
    ax.set_ylabel("Mean reference weight")
    ax.set_ylim(0, 1.0)
    ax.set_yticks([0, 0.5, 1.0])
    ax.set_title("Section-level composition", loc="left", pad=3, fontweight="bold", fontsize=6.3)


def draw_spatial_map_header(ax) -> None:
    panel_label(ax, "d", x=-0.025, y=0.50)
    ax.set_axis_off()
    ax.text(
        0.02,
        0.60,
        "Dominant cell type",
        transform=ax.transAxes,
        ha="left",
        va="center",
        fontsize=6.5,
        fontweight="bold",
    )
    handles = [
        Line2D([0], [0], marker="s", color="none", markerfacecolor=CELL_COLORS[ct], markeredgecolor="none", markersize=4.8)
        for ct in CELL_TYPES
    ]
    labels = [CELL_TYPE_SHORT[ct] for ct in CELL_TYPES]
    ax.legend(
        handles,
        labels,
        loc="center right",
        ncol=4,
        columnspacing=0.55,
        handletextpad=0.25,
        borderaxespad=0,
        fontsize=4.8,
    )


def draw_spatial_maps(fig, subgs, omega) -> None:
    axes = []
    for j, section in enumerate(SECTION_ORDER):
        ax = fig.add_subplot(subgs[0, j])
        axes.append(ax)
        df = omega[section].copy()
        colors = df["dominant_ref_cell_type"].map(CELL_COLORS).fillna("#BDBDBD")
        ax.scatter(df["x"], -df["y"], s=2.2, c=colors, linewidths=0, alpha=0.80, rasterized=True)
        ax.set_aspect("equal")
        ax.set_axis_off()
        ax.set_title(SECTION_LABELS[section], pad=1.5, fontsize=6, fontweight="bold")
    return axes


def draw_loss(ax, history) -> None:
    panel_label(ax, "e", x=-0.18, y=1.03)
    ax.plot(history["round"], history["loss"], color="#0F4D92", lw=1.2)
    ax.scatter(history["round"].iloc[-1], history["loss"].iloc[-1], s=12, color="#0F4D92", zorder=3)
    ax.set_xlabel("Communication round")
    ax.set_ylabel("NB loss")
    ax.set_title("Reference omega AP-FedAdam", loc="left", pad=3, fontweight="bold")
    ax.set_xlim(history["round"].min(), history["round"].max())
    ax.set_ylim(0, max(history["loss"]) * 1.05)
    ax.text(
        0.97,
        0.80,
        f"final\n{history['loss'].iloc[-1]:.2f}",
        transform=ax.transAxes,
        ha="right",
        va="top",
        fontsize=5.4,
        color="#333333",
    )


def draw_top_pairs(ax, ranking) -> None:
    panel_label(ax, "f", x=-0.13, y=1.03)
    top = ranking.head(8).iloc[::-1].copy()
    labels = [str(row.Gene) for _, row in top.iterrows()]
    colors = [CELL_COLORS[row.Cell_Type_Name] for _, row in top.iterrows()]
    y = np.arange(len(top))
    ax.barh(y, top["Abs_Beta_Max"], color=colors, edgecolor="black", linewidth=0.35)
    ax.set_yticks(y)
    ax.set_yticklabels(labels, fontsize=5.2)
    ax.set_xlabel("Max |spatial coefficient|")
    ax.set_title("Top CTSV pairs", loc="left", pad=3, fontweight="bold")
    ax.set_xlim(0, max(top["Abs_Beta_Max"]) * 1.38)
    xmax = max(top["Abs_Beta_Max"])
    for yi, (_, row) in enumerate(top.iterrows()):
        value = row["Abs_Beta_Max"]
        ct = CELL_TYPE_SHORT[row["Cell_Type_Name"]]
        ax.text(value + xmax * 0.025, yi, f"{value:.2f}", va="center", ha="left", fontsize=5.0)
        ax.text(xmax * 1.27, yi, ct, va="center", ha="left", fontsize=5.0, color="#333333")

def save_figure(fig) -> None:
    fig.savefig(FIG_BASE.with_suffix(".svg"), bbox_inches="tight")
    fig.savefig(FIG_BASE.with_suffix(".pdf"), bbox_inches="tight")
    fig.savefig(FIG_BASE.with_suffix(".png"), dpi=450, bbox_inches="tight")
    fig.savefig(FIG_BASE.with_suffix(".tiff"), dpi=600, bbox_inches="tight")


def write_notes(manifest, source_paths, table_paths) -> Path:
    note_path = FIG_DIR / "fig5_mouse_brain_reference_deconv_qa_notes.md"
    lines = [
        "# Figure 5 QA Notes",
        "",
        "## Figure Contract",
        "",
        "- Core conclusion: matched mouse cortex scRNA reference profiles provide reproducible spot-level cell-type weights for the three-section mouse brain AP-FedAdam analysis.",
        "- Archetype: schematic-led composite with spatial-map validation and quantitative downstream evidence.",
        "- Target output: Nature-family two-column figure, 183 mm wide and under 170 mm high.",
        "- Backend: Python/matplotlib only.",
        "- Statistics: descriptive deconvolution weights and coefficient rankings; no formal Wald/FDR inference is claimed for this Mouse Brain figure.",
        "- Image-integrity note: all spatial maps are coordinate scatter plots from processed Visium outputs and NNLS weights; no photographic tissue images or local image adjustments are used.",
        "",
        "## Reference",
        "",
        f"- Reference cells used: {manifest['n_reference_cells_used']}.",
        f"- Label column: `{manifest['label_col']}`.",
        f"- Cell types: {', '.join(manifest['cell_types'])}.",
        "",
        "## Source Data",
        "",
    ]
    for name, path in source_paths.items():
        lines.append(f"- {name}: `{path}`")
    lines += [
        "",
        "## Tables",
        "",
    ]
    for name, path in table_paths.items():
        lines.append(f"- {name}: `{path}`")
    lines += [
        "",
        "## Export Checks",
        "",
        "- SVG and PDF are vector exports with editable text settings (`svg.fonttype=none`, `pdf.fonttype=42`).",
        "- PNG preview was exported at 450 dpi.",
        "- TIFF was exported at 600 dpi for archive/review use; PDF/SVG are preferred for manuscript submission.",
        "",
    ]
    note_path.write_text("\n".join(lines), encoding="utf-8")
    return note_path


def main() -> None:
    configure_matplotlib()
    ref_counts, summary, history, ranking, gene_panel, manifest, omega = load_inputs()
    source_paths = write_source_data(ref_counts, summary, history, ranking, gene_panel, omega)
    table_paths = write_tables(ref_counts, summary, ranking)

    fig = plt.figure(figsize=(7.2, 7.55))
    gs = fig.add_gridspec(
        nrows=6,
        ncols=12,
        height_ratios=[0.82, 0.28, 1.15, 0.22, 1.85, 1.08],
        hspace=0.52,
        wspace=1.65,
    )

    ax_a = fig.add_subplot(gs[0, 0:12])
    draw_workflow(ax_a, manifest)

    ax_b = fig.add_subplot(gs[2, 0:5])
    draw_reference_counts(ax_b, ref_counts)

    ax_c = fig.add_subplot(gs[2, 6:12])
    draw_mean_weights(ax_c, summary)

    ax_d_header = fig.add_subplot(gs[3, 0:12])
    draw_spatial_map_header(ax_d_header)
    map_gs = gs[4, 0:12].subgridspec(1, 3, wspace=0.04)
    draw_spatial_maps(fig, map_gs, omega)

    ax_e = fig.add_subplot(gs[5, 0:4])
    draw_loss(ax_e, history)

    ax_f = fig.add_subplot(gs[5, 5:12])
    draw_top_pairs(ax_f, ranking)

    save_figure(fig)
    plt.close(fig)
    note_path = write_notes(manifest, source_paths, table_paths)

    print(f"Saved figure base: {FIG_BASE}")
    print(f"Saved source data: {SOURCE_DIR}")
    print(f"Saved tables: {TABLE_DIR}")
    print(f"Saved QA notes: {note_path}")


if __name__ == "__main__":
    main()
